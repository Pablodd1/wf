'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const { buildExactCatalogModelMap } = require('../../shared/exact-catalog-model-map.cjs');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const catalogBytes = fs.readFileSync(path.join(root,'public/catalog-source-v1.json'));
const aliasBytes = fs.readFileSync(path.join(root,'shared/published-brand-aliases.json'));
const built = buildExactCatalogModelMap(JSON.parse(catalogBytes).entries);
const registry = { contract: 'WF_EXACT_CATALOG_MODEL_DISPLAY_V1', catalog_file: 'public/catalog-source-v1.json',
  catalog_sha256: sha(catalogBytes), aliases_sha256: sha(aliasBytes),
  semantics: 'Display-only unique source-catalog manufacturer/full-reference model. Source models, reference punctuation and every original listing fact stay unchanged. Multiple distinct model claims are held.',
  exact_pairs: built.exact_pairs, supported_pairs: Object.values(built.models).reduce((n,refs)=>n+Object.keys(refs).length,0),
  models: built.models, rejected: built.rejected };
const registryText = JSON.stringify(registry,null,2)+'\n';
const mapLiteral = JSON.stringify(Object.fromEntries(Object.entries(registry.models).map(([brand,refs])=>[brand,Object.fromEntries(Object.entries(refs).map(([reference,row])=>[reference,row.model]))]))).replaceAll("'","''");
const aliasLiteral = JSON.stringify(JSON.parse(aliasBytes)).replaceAll("'","''");
const sql = `-- Generated by tools/mariadb-live/build-exact-catalog-model-projection.cjs.
-- Source catalog SHA256 ${registry.catalog_sha256}; shared map SHA256 ${sha(registryText)}.
-- Presentation/filter projection only. No publication/candidate/raw/member payload changes.
BEGIN;
SET LOCAL lock_timeout='5s';
CREATE FUNCTION wf_canonical_staging.published_catalog_model_v1(p_model text,p_brand text,p_reference text)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $model$
 SELECT CASE WHEN NULLIF(pg_catalog.btrim(p_model),'') IS NOT NULL THEN p_model ELSE
  '${mapLiteral}'::pg_catalog.jsonb OPERATOR(pg_catalog.->) pg_catalog.lower(COALESCE(
   '${aliasLiteral}'::pg_catalog.jsonb OPERATOR(pg_catalog.->>) pg_catalog.lower(pg_catalog.btrim(p_brand)),pg_catalog.btrim(p_brand)))
   OPERATOR(pg_catalog.->>) pg_catalog.upper(pg_catalog.translate(p_reference,E' \\t\\r\\n\\f\\013','')) END;
$model$;
REVOKE ALL ON FUNCTION wf_canonical_staging.published_catalog_model_v1(text,text,text) FROM PUBLIC,anon,authenticated,service_role;
COMMENT ON FUNCTION wf_canonical_staging.published_catalog_model_v1(text,text,text) IS
 'WF_EXACT_CATALOG_MODEL_DISPLAY_V1; catalog_sha256=${registry.catalog_sha256}; map_sha256=${sha(registryText)}';
DO $filters$
DECLARE item record; definition text; updated text; changed integer=0;
BEGIN
 FOR item IN SELECT p.oid,p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
 WHERE (n.nspname='public' AND p.proname=ANY(ARRAY[
  'get_trading_floor_canary_keyset_v4','get_trading_floor_snapshot_count','get_trading_floor_discovery_keyset_v1','get_trading_floor_source_images_keyset_v1',
  'get_price_research_snapshot_count','get_price_research_snapshot_facets','get_price_research_snapshot_dial_facets',
  'get_price_research_snapshot_stats','get_price_research_canary_keyset_v4','get_price_research_wtb_demand_v3','get_price_research_snapshot_membership']))
 OR (n.nspname='wf_canonical_staging' AND p.proname='compute_research_snapshot_breakdown_v2')
 LOOP
  definition=pg_get_functiondef(item.oid);
  updated=regexp_replace(definition,$pattern$(m|member)\\.payload[[:space:]]*->>[[:space:]]*'model'$pattern$,
   $replace$wf_canonical_staging.published_catalog_model_v1(\\1.payload->>'model',\\1.payload->>'brand',\\1.payload->>'reference')$replace$,'g');
  updated=regexp_replace(updated,$pattern$\\mv\\.model\\M$pattern$,
   $replace$wf_canonical_staging.published_catalog_model_v1(v.model,v.brand,v.reference)$replace$,'g');
  updated=regexp_replace(updated,
   $pattern$lower\\((wf_canonical_staging\\.published_catalog_model_v1\\([^)]*\\))\\)[[:space:]]*=[[:space:]]*lower\\(p_model\\)$pattern$,
   $replace$COALESCE(lower(\\1),'reference-only listings')=lower(p_model)$replace$,'g');
  IF updated=definition THEN RAISE EXCEPTION 'catalog_model_filter_definition_mismatch: %',item.proname; END IF;
  EXECUTE updated;changed=changed+1;
 END LOOP;
 IF changed<>12 THEN RAISE EXCEPTION 'catalog_model_filter_function_count_mismatch: %',changed; END IF;
 SELECT pg_get_functiondef('public.get_canary_snapshot_browse_v1(uuid,text,text,text)'::regprocedure) INTO definition;
 updated=replace(definition,
  $old$wf_canonical_staging.published_browse_brand_v1(brand) brand,model,reference$old$,
  $new$wf_canonical_staging.published_browse_brand_v1(brand) brand,wf_canonical_staging.published_catalog_model_v1(model,brand,reference) model,reference$new$);
 IF updated=definition THEN RAISE EXCEPTION 'catalog_model_browse_definition_mismatch'; END IF;
 EXECUTE updated;
END $filters$;
NOTIFY pgrst,'reload schema';
COMMIT;
`;
for (const [relative, text] of [['shared/exact-catalog-models.json',registryText],['supabase/migrations/20260910300000_exact_catalog_model_display.sql',sql]]) {
  const file=path.join(root,relative);
  if (process.argv.includes('--check')) { if (!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text) throw new Error('Generated catalog projection differs: '+relative); }
  else fs.writeFileSync(file,text);
}
console.log(JSON.stringify({status:'PASS_EXACT_CATALOG_MODEL_PROJECTION_GENERATION',catalog_sha256:registry.catalog_sha256,map_sha256:sha(registryText),exact_pairs:registry.exact_pairs,supported_pairs:registry.supported_pairs,rejected_pairs:registry.rejected.length}));
