-- Canonical, source-backed dealer directory for QNSA.
-- This migration never rewrites immutable raw messages or staging listings.
-- Public activity is attached only through exact verified identities and an
-- explicit link ledger populated from already-released marketplace rows.

BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.dealers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text,
  display_name text,
  company_name text,
  country_code text,
  city text,
  rating numeric(3,2),
  review_count integer NOT NULL DEFAULT 0,
  whatsapp_group_count integer NOT NULL DEFAULT 0,
  avatar_url text,
  profile_summary text,
  status text NOT NULL DEFAULT 'UNVERIFIED',
  contact_consent boolean NOT NULL DEFAULT false,
  verified_at timestamptz,
  member_since text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  last_synced_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.dealers
  ADD COLUMN IF NOT EXISTS slug text,
  ADD COLUMN IF NOT EXISTS company_name text,
  ADD COLUMN IF NOT EXISTS country_code text,
  ADD COLUMN IF NOT EXISTS city text,
  ADD COLUMN IF NOT EXISTS rating numeric(3,2),
  ADD COLUMN IF NOT EXISTS review_count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS whatsapp_group_count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS avatar_url text,
  ADD COLUMN IF NOT EXISTS profile_summary text,
  ADD COLUMN IF NOT EXISTS member_since text,
  ADD COLUMN IF NOT EXISTS metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS last_synced_at timestamptz,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS idx_qnsa_dealers_slug
  ON public.dealers (lower(slug)) WHERE slug IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_qnsa_dealers_directory_order
  ON public.dealers (review_count DESC, display_name, id)
  WHERE status = 'VERIFIED';

CREATE TABLE IF NOT EXISTS public.dealer_source_identities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id uuid NOT NULL REFERENCES public.dealers(id) ON DELETE CASCADE,
  source_system text NOT NULL,
  source_identity text NOT NULL,
  identity_type text NOT NULL,
  verification_status text NOT NULL DEFAULT 'UNVERIFIED',
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_system, source_identity, identity_type)
);

CREATE OR REPLACE FUNCTION public.normalize_seller_phone_identity(p_value text)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path = '' AS $$
  SELECT CASE
    WHEN regexp_replace(COALESCE(p_value, ''), '[^0-9]', '', 'g') ~ '^[0-9]{8,15}$'
      THEN regexp_replace(COALESCE(p_value, ''), '[^0-9]', '', 'g')
    ELSE NULL
  END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_qnsa_dealer_verified_phone
  ON public.dealer_source_identities (
    public.normalize_seller_phone_identity(source_identity)
  )
  WHERE verification_status = 'VERIFIED'
    AND upper(identity_type) IN ('PHONE', 'WHATSAPP')
    AND public.normalize_seller_phone_identity(source_identity) IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_qnsa_dealer_source_profile
  ON public.dealer_source_identities (source_system, source_identity)
  WHERE upper(identity_type) = 'SOURCE_PROFILE';

CREATE TABLE IF NOT EXISTS public.dealer_directory_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id uuid NOT NULL REFERENCES public.dealers(id) ON DELETE CASCADE,
  source_system text NOT NULL,
  source_profile_id text NOT NULL,
  captured_at timestamptz NOT NULL,
  source_rank integer,
  wts_count integer,
  wtb_count integer,
  group_count integer,
  review_count integer,
  positive_feedback_count integer,
  negative_feedback_count integer,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  imported_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_system, source_profile_id, captured_at)
);

CREATE TABLE IF NOT EXISTS public.dealer_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id uuid NOT NULL REFERENCES public.dealers(id) ON DELETE CASCADE,
  source_system text NOT NULL,
  source_review_key text NOT NULL,
  reviewer_name text,
  review_date text,
  sentiment text,
  rating numeric(3,2),
  source_published boolean NOT NULL DEFAULT true,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dealer_id, source_system, source_review_key)
);

CREATE TABLE IF NOT EXISTS public.dealer_group_memberships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dealer_id uuid NOT NULL REFERENCES public.dealers(id) ON DELETE CASCADE,
  source_system text NOT NULL,
  group_identity text NOT NULL,
  group_name text,
  platform text,
  membership_status text NOT NULL DEFAULT 'OBSERVED',
  source_published boolean NOT NULL DEFAULT false,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  UNIQUE (dealer_id, source_system, group_identity)
);

CREATE TABLE IF NOT EXISTS public.dealer_listing_links (
  listing_id uuid PRIMARY KEY,
  source_record_id text,
  dealer_id uuid NOT NULL REFERENCES public.dealers(id) ON DELETE RESTRICT,
  source_system text NOT NULL,
  source_identity text NOT NULL,
  link_method text NOT NULL CHECK (link_method IN ('EXACT_VERIFIED_PHONE', 'AUTHENTICATED_SUBMISSION')),
  link_status text NOT NULL DEFAULT 'APPLIED' CHECK (link_status IN ('APPLIED', 'REVOKED')),
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  linked_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_qnsa_dealer_listing_links_profile
  ON public.dealer_listing_links (dealer_id, link_status, listing_id);

ALTER TABLE public.dealers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dealer_source_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dealer_directory_snapshots ENABLE ROW LEVEL SECURITY;
