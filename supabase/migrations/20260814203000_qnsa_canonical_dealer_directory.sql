  public.qnsa_dealer_directory_page(text, integer, integer),
  public.qnsa_dealer_profile(text, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.apply_qnsa_dealer_directory_snapshot(jsonb),
  public.apply_qnsa_dealer_listing_links(jsonb),
  public.qnsa_dealer_directory_page(text, integer, integer),
  public.qnsa_dealer_profile(text, integer, integer)
  TO service_role;

COMMIT;
