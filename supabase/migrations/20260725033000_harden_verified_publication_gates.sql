CREATE OR REPLACE FUNCTION public.verified_listing_thumbnail(p_record_id TEXT)
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH expected AS (
    SELECT
      w.id,
      COALESCE(NULLIF(r.canonical_brand, ''), w.brand) AS brand,
      COALESCE(NULLIF(r.canonical_model, ''), w.model) AS model,
      COALESCE(NULLIF(r.canonical_reference, ''), w.reference) AS reference,
      COALESCE(NULLIF(r.canonical_dial_color, ''), w.dial_color) AS dial_color
    FROM public.watch_records w
    JOIN public.listing_identity_reviews r
      ON r.record_id = w.id
     AND r.status IN ('CATALOG_CONFIRMED', 'HUMAN_APPROVED')
    WHERE w.id = p_record_id
  )
  SELECT m.public_url
  FROM expected x
  JOIN public.listing_image_reviews r ON r.record_id = x.id
  JOIN public.media_manifest m
    ON m.source_object_key = r.source_object_key
   AND m.matched_record_id = r.record_id
  WHERE r.status = 'VISUALLY_VERIFIED'
    AND lower(trim(r.identity_snapshot->>'brand')) = lower(trim(x.brand))
    AND lower(trim(r.identity_snapshot->>'model')) = lower(trim(x.model))
    AND lower(trim(r.identity_snapshot->>'reference')) = lower(trim(x.reference))
    AND lower(trim(r.identity_snapshot->>'dial_color')) = lower(trim(x.dial_color))
  ORDER BY r.reviewed_at DESC NULLS LAST, r.source_object_key
  LIMIT 1;
$$;

CREATE OR REPLACE VIEW public.trading_floor_verified_listings
WITH (security_invoker = true) AS
SELECT
  m.id,
  COALESCE(NULLIF(r.canonical_brand, ''), w.brand) AS brand,
  COALESCE(NULLIF(r.canonical_reference, ''), w.reference) AS reference,
  COALESCE(NULLIF(r.canonical_dial_color, ''), w.dial_color) AS dial_color,
  m.condition,
  m.year,
  m.price_raw,
  m.price_usd,
  m.currency,
  m.confidence,
  m.verdict,
  m.source,
  m.source_type,
  m.listing_type,
  m.listing_date,
  m.listing_status,
  m.created_at,
  public.verified_listing_thumbnail(m.id) IS NOT NULL AS has_images,
  public.verified_listing_thumbnail(m.id) AS thumbnail_url,
  m.region,
  COALESCE(NULLIF(r.canonical_model, ''), w.model) AS model,
  CASE
    WHEN public.verified_listing_thumbnail(m.id) IS NULL THEN '[]'::jsonb
    ELSE jsonb_build_array(public.verified_listing_thumbnail(m.id))
  END AS image_urls
FROM public.trading_floor_market_listings m
JOIN public.watch_records w ON w.id = m.id
JOIN public.listing_identity_reviews r
  ON r.record_id = m.id
 AND r.status IN ('CATALOG_CONFIRMED', 'HUMAN_APPROVED');

