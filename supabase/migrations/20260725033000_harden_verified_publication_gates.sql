CREATE OR REPLACE FUNCTION public.is_unsplit_bundle_parent(p_source_record_id TEXT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.normalization_shadow_v4 shadow
    WHERE shadow.source_record_id = p_source_record_id
      AND (
        shadow.candidate_count > 1
        OR 'BUNDLE_SPLIT_REQUIRED' = ANY(COALESCE(shadow.change_flags, ARRAY[]::TEXT[]))
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.is_verified_listing_dealer_lineage(
  p_record_id TEXT,
  p_dealer_id UUID
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.seller_listing_lineage_staging s
    WHERE s.source_record_id = p_record_id
      AND s.matched_dealer_id = p_dealer_id
      AND s.match_status = 'APPLIED'
  );
$$;

REVOKE ALL ON FUNCTION public.is_unsplit_bundle_parent(TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.is_verified_listing_dealer_lineage(TEXT, UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_unsplit_bundle_parent(TEXT) TO anon, authenticated, service_role;
